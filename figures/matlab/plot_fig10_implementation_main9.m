%% Fig. 10 | FPGA latency and routed headroom: rev T vs local A12
% MATLAB R2021b, base MATLAB only. No toolbox required.
%
% REQUIRED INPUT (place alongside this .m file):
%   fig_implementation_closure_source.json
%
% OUTPUTS:
%   fig10_matlab_publication.fig  - native editable MATLAB figure
%   fig10_matlab_publication.pdf  - vector PDF
%   fig10_matlab_publication.svg  - vector SVG
%   fig10_matlab_publication.png  - 600 dpi preview
%
% DATA CONTRACT / WHAT THE FIGURE DOES NOT CLAIM:
% (a) HLS 2022.2 single-call cycle estimates / configured 58,333-cycle
%     slot budget. Rev M and rev T use the same corrected checkpoint and
%     HLS 2022.2; these are estimates, not measured board streaming rates.
% (b) Post-route unused resources, calculated as 100*(limit-used)/limit.
%     Separate rev-T and A12 integrated self-test builds (one each).
%     No cross-design error bars: physical builds were not replicated.
%     Right column contains the archived A12 unused *counts*.
% Timing note is post-route WNS at 100 MHz, not a power/rate measure.
%
clearvars; close all; clc;
rootDir = fileparts(mfilename('fullpath'));
if isempty(rootDir), rootDir = pwd; end
sourcePath = fullfile(rootDir,'fig_implementation_closure_source.json');
assert(exist(sourcePath,'file')==2,'Cannot find Fig.10 JSON: %s',sourcePath);
D = jsondecode(fileread(sourcePath));
assert(strcmp(char(D.figure),'fig_implementation_closure'), ...
    'Wrong JSON: expected fig_implementation_closure.');

% Recorded HLS cycle estimates are ordered rev M, W8A8 rev T, local A12.
cycles = double(D.latency_cycles(:));
budget = double(D.budget_cycles);
assert(numel(cycles)==3 && all(isfinite(cycles)) && ...
    all(cycles>0) && isfinite(budget) && budget>0, ...
    'Missing/invalid HLS cycle values or budget.');
latencyPercent = 100*cycles/budget;
assert(all(abs(cycles-[69504;58115;58115])<1e-9) && budget==58333, ...
    'Unexpected source revision: inspect Fig.10 data contract.');

% The plotting order is top to bottom: BRAM18 eq., slices, LUTs, FFs, DSPs.
fields = {'bram18_equivalents','slices','lut','ff','dsp'};
rowNames = {'BRAM18 eq.','Slices','LUTs','FFs','DSPs'};
lim = zeros(5,1); usedT = zeros(5,1); usedA = zeros(5,1);
remainingDeclared = zeros(5,1);
for i=1:5
    key = fields{i};
    lim(i) = double(D.physical.limits.(key));
    usedT(i) = double(D.physical.rev_t.(key));
    usedA(i) = double(D.physical.local_a12.(key));
    remainingDeclared(i) = double(D.physical.unused_a12_capacity.(key));
end
assert(logical(D.physical.rev_t.design_routed) && ...
    logical(D.physical.local_a12.design_routed), ...
    'This plot requires both routed builds.');
assert(all(lim>0) && all(usedT>=0) && all(usedA>=0) ...
    && all(usedT<=lim) && all(usedA<=lim), ...
    'Invalid resource totals or capacities.');
unusedT = lim-usedT;
unusedA = lim-usedA;
assert(isequal(unusedA,remainingDeclared), ...
    'A12 remaining counts disagree with the archived source.');
pctT = 100*unusedT./lim;
pctA = 100*unusedA./lim;
assert(all(isfinite(pctT)) && all(isfinite(pctA)) && ...
    all(pctT>0) && all(pctA>0),'Log-scale headroom must be positive.');
assert(D.timing.rev_t.wns_ns>0 && D.timing.local_a12.wns_ns>0, ...
    'Unexpected post-route setup timing values.');

% Restrained publication palette, coordinated with Figs. 5-8.
navy    = [0.12 0.27 0.40];
copper  = [0.78 0.34 0.18];
teal    = [0.05 0.47 0.48];
slate   = [0.44 0.51 0.57];
muted   = [0.35 0.41 0.47];
gridC   = [0.87 0.89 0.91];
neutral = [0.58 0.63 0.67];

figW = 18.0; figH = 13.0;             % 180 x 130 mm, double-column figure.
fig = figure('Name','Fig. 10 / FPGA closure', ...
    'Units','centimeters','Position',[2.0 1.6 figW figH], ...
    'PaperUnits','centimeters','PaperSize',[figW figH], ...
    'PaperPosition',[0 0 figW figH], ...
    'Renderer','painters','InvertHardcopy','off','Color','w');

%% (a) Configured slot latency relative to deadline (linear percent axis).
axA = axes('Parent',fig,'Units','centimeters', ...
    'Position',[4.25 8.63 12.85 2.61]);
hold(axA,'on');
set(axA,'FontName','Arial','FontSize',9.0,'Box','off','Layer','top', ...
    'Color','w','LineWidth',0.74,'TickDir','out', ...
    'XColor',navy,'YColor',navy);
xlim(axA,[0 129]); ylim(axA,[0.50 3.70]);
set(axA,'XTick',[0 25 50 75 100 125], ...
    'YTick',[1 2 3], ...
    'YTickLabel',{'Local A12','W8A8 rev T','Matched rev-M'}, ...
    'TickLabelInterpreter','none');

% Draw three independent bars in the order of the archived cycle estimates.
plotRow = [3;2;1];
barColors = {slate,navy,copper};
for i=1:3
    xRight = latencyPercent(i); y = plotRow(i);
    patch(axA,[0 xRight xRight 0], ...
          [y-0.235 y-0.235 y+0.235 y+0.235],barColors{i}, ...
          'EdgeColor','none','HandleVisibility','off');
    % Absolute cycle numbers, safely placed inside the bars.
    text(axA,0.55*xRight,y,sprintf('%s cycles',formatInteger(cycles(i))), ...
        'FontName','Arial','FontSize',8.7,'FontWeight','bold', ...
        'HorizontalAlignment','center','VerticalAlignment','middle', ...
        'Color','w','Interpreter','none');
end
% 100% is a SLOT DEADLINE, not an observed throughput measurement.
line(axA,[100 100],[0.55 3.53],'LineStyle','--','Color',neutral, ...
    'LineWidth',1.05,'HandleVisibility','off');
text(axA,101.2,3.53,'100% deadline','Color',muted,'FontName','Arial', ...
    'FontSize',8.0,'VerticalAlignment','middle');
xlabel(axA,'HLS cycles / configured slot budget (%)', ...
    'FontName','Arial','FontSize',9.0,'Color',navy);

%% (b) Post-route UNUSED capacity on a log-percent axis, not occupancy.
axB = axes('Parent',fig,'Units','centimeters', ...
    'Position',[4.25 3.00 8.77 3.38]);
hold(axB,'on');
set(axB,'FontName','Arial','FontSize',9.0,'Box','off','Layer','top', ...
    'Color','w','LineWidth',0.74,'TickDir','out', ...
    'XColor',navy,'YColor',navy,'XScale','log');
xlim(axB,[1 110]); ylim(axB,[0.48 5.56]);
set(axB,'XTick',[1 2 5 20 100], ...
    'XTickLabel',{'1','2','5','20','100'}, ...
    'YTick',1:5,'YTickLabel',rowNames(end:-1:1), ...
    'TickLabelInterpreter','none');

rowY = (5:-1:1)';
for i=1:5
    y=rowY(i);
    % Thin rows, not fabricated confidence intervals or connections.
    line(axB,[1 110],[y-0.49 y-0.49], ...
        'Color',gridC,'LineStyle',':','LineWidth',0.55, ...
        'HandleVisibility','off');
    plot(axB,pctT(i),y+0.135,'o', ...
        'Color',navy,'MarkerFaceColor','w', ...
        'MarkerSize',6.5,'LineWidth',1.25, ...
        'HandleVisibility','off');
    plot(axB,pctA(i),y-0.135,'d', ...
        'Color',copper,'MarkerFaceColor',copper, ...
        'MarkerSize',6.3,'LineWidth',1.05, ...
        'HandleVisibility','off');
end
xlabel(axB,'Unused device capacity (%) - logarithmic scale', ...
    'FontName','Arial','FontSize',9.0,'Color',navy);

% Separate right column: counts have distinct units, so do not share an axis.
axCounts = axes('Parent',fig,'Units','centimeters', ...
    'Position',[13.45 3.00 3.45 3.38], ...
    'Color','none','Visible','off');
set(axCounts,'XLim',[0 3.45],'YLim',[0.48 5.56]);
hold(axCounts,'on');
for i=1:5
    text(axCounts,1.63,rowY(i),formatInteger(unusedA(i)), ...
        'Color',navy,'FontName','Arial','FontSize',9.2, ...
        'HorizontalAlignment','center','VerticalAlignment','middle', ...
        'Interpreter','none');
end

% Figure-wide annotations in physical cm, independent of MATLAB legends.
axText = axes('Parent',fig,'Units','centimeters', ...
    'Position',[0 0 figW figH],'Color','none','Visible','off');
set(axText,'XLim',[0 figW],'YLim',[0 figH]);
hold(axText,'on');
text(axText,0.78,12.15,'(a) Core HLS latency vs. slot budget', ...
    'FontName','Arial','FontSize',10.5,'FontWeight','bold','Color',navy);
text(axText,0.78,7.22, ...
    'Matched rev-M / rev T: corrected-PDP checkpoint; HLS 2022.2; deadline: 58,333 cycles.', ...
    'FontName','Arial','FontSize',8.2,'Color',muted, ...
    'Interpreter','none');
text(axText,0.78,6.72,'(b) Post-route remaining FPGA capacity', ...
    'FontName','Arial','FontSize',10.5,'FontWeight','bold','Color',navy);
text(axText,15.18,6.60,{'A12 remaining','(raw units)'}, ...
    'FontName','Arial','FontSize',8.5,'FontWeight','bold', ...
    'HorizontalAlignment','center','VerticalAlignment','bottom', ...
    'Color',navy);

% Manual legend: no automatic resizing or overlap with plot axes.
plot(axText,4.45,1.79,'o','Color',navy,'MarkerFaceColor','w', ...
    'MarkerSize',6.7,'LineWidth',1.2);
text(axText,4.72,1.79,'W8A8 rev T', ...
    'FontName','Arial','FontSize',8.5,'Color',navy, ...
    'VerticalAlignment','middle');
plot(axText,8.75,1.79,'d','Color',copper,'MarkerFaceColor',copper, ...
    'MarkerSize',6.3,'LineWidth',1.1);
text(axText,9.03,1.79,'Local A12', ...
    'FontName','Arial','FontSize',8.5,'Color',navy, ...
    'VerticalAlignment','middle');
text(axText,0.78,1.30, ...
    sprintf('Local A12 - rev T: +%d LUT; +%d FF; +%d slices; +%d DSP; +%d BRAM18 eq.', ...
       round(usedA(3)-usedT(3)), round(usedA(4)-usedT(4)), ...
       round(usedA(2)-usedT(2)), round(usedA(5)-usedT(5)), ...
       round(usedA(1)-usedT(1))), ...
    'FontName','Arial','FontSize',8.25,'Color',muted);
text(axText,0.78,0.88, ...
    sprintf('Post-route WNS at 100 MHz: rev T +%.3f ns; A12 +%.3f ns.', ...
       double(D.timing.rev_t.wns_ns),double(D.timing.local_a12.wns_ns)), ...
    'FontName','Arial','FontSize',8.25,'Color',muted);
text(axText,0.78,0.44, ...
    'A12 JTAG: finite-vector self-test passed; streaming and measured board power remain unverified.', ...
    'FontName','Arial','FontSize',8.0,'Color',muted, ...
    'Interpreter','none');

%% Preserve editability and export without user interaction.
outputBase = fullfile(rootDir,'fig10_matlab_publication');
savefig(fig,[outputBase '.fig']);
print(fig,[outputBase '.pdf'],'-dpdf','-painters');
print(fig,[outputBase '.svg'],'-dsvg','-painters');
print(fig,[outputBase '.png'],'-dpng','-r600');

fprintf('Fig.10 saved: %s.[fig/pdf/svg/png]\n',outputBase);
fprintf('HLS cycles: rev M %.0f; rev T %.0f; A12 %.0f; budget %.0f.\n', ...
    cycles(1),cycles(2),cycles(3),budget);
fprintf('rev T/A12 margin to configured budget: %.0f cycles.\n', budget-cycles(3));
fprintf('A12 unused [BRAM18eq, slices, LUT, FF, DSP] = [%d %d %d %d %d].\n', ...
    round(unusedA(1)),round(unusedA(2)),round(unusedA(3)), ...
    round(unusedA(4)),round(unusedA(5)));

%% Local helper for readable thousands grouping (portable formatting).
function s = formatInteger(x)
    s = sprintf('%.0f', double(x));
    for k=(numel(s)-2):-3:2
        s = [s(1:k-1) ',' s(k:end)]; %#ok<AGROW>
    end
end

