/* Local A12 candidate, 2026-10-02. Only m_back output changes from rev-T.
 * Quantization is signed symmetric 12-bit, stored in int16_t containers.
 * All legacy history below describes rev-T, NOT proof for this candidate.
 * Candidate evidence must come from the local validation and tool reports.
 */
/* receiver_opt_rev_t.cpp - isolated corrected-PDP area experiment.
 *
 * Algorithm = s_r0_slim QAT W8A8 (same as receiver.c golden model).
 * E5b-2 kept a float MAC/requant datapath: every dense layer ran at II=4
 * (float fadd recurrence) which left ~1.7M cycles/slot, and the in-place
 * FFT butterfly grew 64:1 register mux trees (78k LUT, -24 ns slack).
 *
 * E5b-3 changes (all validated against stim.h, statistical equivalence):
 *   [P1] INT8-index GEMM: requantized activations are stored as their INT8
 *        grid indices (ap_int<8>), dense layers accumulate INTEGER products
 *        (int8 x int8, explicitly bound to DSP for the four main GEMMs),
 *        per-row scales
 *        are hoisted out of the inner loop and folded into one float FMA
 *        per output.  Value reconstruction qv(q,s)=q*s is bit-identical to
 *        the golden rq() return value.
 *   [P2] ping-pong FFT: each radix-2 stage reads src / writes dst arrays
 *        (no in-place read-modify-write), ram_t2p so 2R+2W fit one cycle.
 *        One shared instance (INLINE off) serves both CP-DFT legs + CP-IDFT.
 *   [P3] requant without fptosi: RNE via mantissa extraction after a
 *        1.5*2^23 magic add (q8()); the int8 result drops out of the
 *        mantissa bits.  rintf in lut_idx replaced the same way; pwla_tanh
 *        index uses ap_fixed<8,5> truncation instead of a float->int core
 *        (<8,4> wraps for t>=8: fixed 09/05, found by per-layer diff).
 *   [P4] storage: all inter-layer activations are 8-bit, weight ROMs
 *        cyclic-partitioned to feed the unrolled MACs (m_front/m_back
 *        U=16, c_in/c_out U=32, residual U=8).
 *   [P5] 4-partial accumulator in the rms-norm loops (II=4 -> II=1) and
 *        p*(1/FS) instead of p/FS (kills the fabric fdiv core).
 *
 * Post-csynth revisions (per-report QoR feedback loop):
 *   rev A (as above): 103,087 cyc, 232k LUT (435%), -1.78 ns.
 *   rev B: FFT-internal storage dft_t ap_fixed<28,12> -> float.  The
 *        fixed<->float conversion cores on every butterfly read/write
 *        were ~90% of FFT area (fft64: 76.5k -> ~7.5k LUT per copy);
 *        float is also strictly more accurate, mismatch 23 -> 16 bits.
 *        GEMM accumulator `= {0}` initializers replaced by init-on-first-
 *        iteration selects: the initializer synthesizes a 16/32-cycle
 *        clearing loop per output row (34 of 54 cycles in c_out).
 *        -> 63,971 cyc, 83.7k LUT, 54.2k FF.
 *   rev C: attempted fft64 sharing via ALLOCATION limit=1 — ignored by
 *        HLS 2022.1 (call sites inside INLINE-off subfunctions), no change.
 *   rev D: GEMM weight ROMs packed 4 x int8 per uint32 word (weights_pack.h,
 *        generated by pack_weights.py).  Cyclic-partitioned int8 banks
 *        waste BRAM18 4x (MF_W_R: 16 banks x 256 B, each a full 2.3 KB
 *        BRAM18 = 32 BRAM for 8 KB; COUT_W 128 BRAM).  Word banks with
 *        factor U/4 cut bank count 4x at identical latency; unpack is
 *        wire slicing.  Bit-exact vs rev B.
 *
 *   rev E (fit xc7z020: rev D was BRAM 313/111%, LUT 83.8k/157%, slack
 *        -1.78 ns): the packing itself saved little because HLS pads each
 *        partitioned bank up to a power of two (COUT: 6272->8192 words =>
 *        16 BRAM18 x 8 banks = 128 for 98 of data).  50176 = 7*7168, so
 *        factor 7 cuts the padding loss (128->112; CIN 64->56, CR 8->7).
 *        [T2] fft64 time-multiplexed across all 3 CP legs: wrappers are
 *        inlined and share top-level staging buffers, one fft64 instance
 *        (was 2x 7.7k LUT + 24 DSP + 10 BRAM), and inside fft64 the six
 *        sequential stage loops share their fmul/fadd/fsub units
 *        (ALLOCATION operation) - 24 DSP + ~6k LUT -> 4 DSP + ~2k LUT.
 *        [T3] all int8 GEMM multipliers moved to DSP (fabric mults were
 *        9.2k+9.2k+4.4k+4.4k LUT); m_front/m_back unroll 16->8 (their
 *        accumulators halve too).  [T4] sqrtf-then-square in both rms
 *        norms and the complex divider replaced by the direct sum of
 *        squares (golden uses hypotf^2 = |y|^2 mathematically; <=2 ulp
 *        deviation, absorbed by the 16-entry LUT buckets) - this was the
 *        only -1.78 ns path and forced II=4.  [T5] per-row scale folding
 *        fused into the GEMM row loop (ACC/ACCO buffers deleted).
 *
 * Remaining known deviations vs the golden model (all requant-boundary
 * flips, absorbed by the statistical-equivalence criteria of tb_opt.cpp):
 * integer GEMM summation vs float product-sum, 4-partial norm summation,
 * direct x*x+y*y vs hypotf^2 (<=2 ulp), FFT-vs-FD with float storage
 * (tighter than the E5b-2 <28,12> deviation).
 */

