%% Fig. 5 v4 fixed — BER vs SNR + paired 2%-BER threshold penalties
% MATLAB R2021b-compatible publication-style redraw.
% Source: fig_ber_paired_b1_longcp_source.json
%
% V4 layout changes:
%   * Panel (c) is a horizontal forest-style effect plot: one comparison per row.
%   * Seed 1/2/3 are shown as small open markers with slight vertical offsets.
%   * Mean +/- sample SD is shown by a filled diamond and horizontal whisker.
%   * Shared 9-method BER legend stays between the top panels and panel (c).
%   * No statistical values are recomputed or modified.
%
% IMPORTANT STATISTICAL CONTRACT
%   * BER point = arithmetic mean across 3 independently trained/evaluated seeds.
%   * Whisker = sample SD across the 3 seeds (not CI).
%   * Curves connect measured SNR points only: no smoothing / imputation.
%   * Panel (c) reads precomputed paired seed-wise 2%-BER threshold differences.
%
% Outputs:
%   fig5_matlab_publication_v4_fixed.pdf
%   fig5_matlab_publication_v4_fixed.svg
%   fig5_matlab_publication_v4_fixed.png

clear; close all; clc;

%% Locate and load JSON
scriptDir = fileparts(mfilename('fullpath'));
if isempty(scriptDir)
    scriptDir = pwd;
end
jsonFile = fullfile(scriptDir, 'fig_ber_paired_b1_longcp_source.json');
assert(isfile(jsonFile), 'JSON file not found: %s', jsonFile);

D = jsondecode(fileread(jsonFile));
assert(isfield(D,'panels') && isfield(D.panels,'EVA') && isfield(D.panels,'ETU'), ...
    'JSON does not contain both EVA and ETU panels.');
assert(isfield(D,'paired_threshold_differences'), ...
    'JSON does not contain paired_threshold_differences.');

%% Publication geometry — manual axes positions for stable R2021b export
fig = figure('Color','w', 'Units','centimeters', ...
    'Position',[2 2 19.0 12.2], 'Renderer','painters');

fontName = 'Helvetica';
fontSize = 8.2;
axisLineWidth = 0.75;
mainLineWidth = 1.35;
refLineWidth  = 0.95;
errorLineWidth = 0.60;
markerSizeMain = 4.7;
markerSizeRef  = 4.0;

% Normalized figure coordinates: [left bottom width height]
ax1 = axes(fig,'Position',[0.075 0.595 0.385 0.335]);
ax2 = axes(fig,'Position',[0.535 0.595 0.385 0.335]);
ax3 = axes(fig,'Position',[0.135 0.085 0.785 0.315]);

%% Methods and restrained palette
methods = { ...
    'dense_fp32', ...
    'structured_fp32', ...
    'structured_w8a8', ...
    'pdp_wiener', ...
    'ls_spline', ...
    'ideal_lmmse', ...
    'almmse', ...
    'ls_cp', ...
    'perfect_csi'};

labels = cell(size(methods));
for k = 1:numel(methods)
    labels{k} = D.method_display_names.(methods{k});
end

C = [ ...
    0.36 0.63 0.78;  % Dense FP32
    0.05 0.32 0.58;  % Structured FP32
    0.82 0.34 0.12;  % Structured W8A8
    0.08 0.53 0.43;  % PDP-aware Wiener
    0.55 0.55 0.55;  % LS-spline
    0.48 0.31 0.56;  % Oracle LMMSE
    0.55 0.49 0.24;  % ALMMSE
    0.35 0.35 0.35;  % LS-CP
    0.08 0.08 0.08]; % Perfect CSI

lineStyles = {'-','-','-','--',':','-.','--',':','-.'};
markers    = {'o','s','d','^','v','>','<','p','*'};
isMain = ismember(methods, {'dense_fp32','structured_fp32','structured_w8a8','pdp_wiener'});

%% Panel (a): EVA
hMethod = plotBerPanel(ax1, D.panels.EVA, methods, C, lineStyles, markers, ...
    isMain, D.target_ber_reference_line, ...
    mainLineWidth, refLineWidth, errorLineWidth, markerSizeMain, markerSizeRef);
formatBerAxes(ax1, '(a) EVA', fontName, fontSize, axisLineWidth);

%% Panel (b): ETU
plotBerPanel(ax2, D.panels.ETU, methods, C, lineStyles, markers, ...
    isMain, D.target_ber_reference_line, ...
    mainLineWidth, refLineWidth, errorLineWidth, markerSizeMain, markerSizeRef);
formatBerAxes(ax2, '(b) ETU', fontName, fontSize, axisLineWidth);
ylabel(ax2,'');

%% Shared BER-method legend — deliberately placed between rows
lgd = legend(ax1, hMethod, labels, ...
    'NumColumns',5, 'Box','off', ...
    'FontName',fontName, 'FontSize',fontSize-0.7);
lgd.Units = 'normalized';
lgd.Position = [0.095 0.472 0.810 0.080];
lgd.ItemTokenSize = [16 7];

%% Panel (c): paired 2%-BER threshold penalty — forest-style effect plot
hold(ax3,'on'); box(ax3,'on');

P = D.paired_threshold_differences;
seedVals = [ ...
    P.EVA.structured_fp32.per_seed_db(:), ...
    P.EVA.pdp_wiener.per_seed_db(:), ...
    P.ETU.structured_fp32.per_seed_db(:), ...
    P.ETU.pdp_wiener.per_seed_db(:)];
meanVals = [ ...
    P.EVA.structured_fp32.mean_db, ...
    P.EVA.pdp_wiener.mean_db, ...
    P.ETU.structured_fp32.mean_db, ...
    P.ETU.pdp_wiener.mean_db];
sdVals = [ ...
    P.EVA.structured_fp32.sample_sd_db, ...
    P.EVA.pdp_wiener.sample_sd_db, ...
    P.ETU.structured_fp32.sample_sd_db, ...
    P.ETU.pdp_wiener.sample_sd_db];

% One comparison per row.  This reads much more clearly than four x-axis groups.
yRow = [4 3 2 1];
yOffset = [0.11 0 -0.11];
seedMarkers = {'o','s','^'};
seedHandles = gobjects(1,3);
seedEdge = [0.28 0.28 0.28];

for s = 1:3
    seedHandles(s) = plot(ax3, seedVals(s,:), yRow + yOffset(s), ...
        'LineStyle','none', ...
        'Marker',seedMarkers{s}, ...
        'MarkerSize',4.8, ...
        'MarkerFaceColor','w', ...
        'MarkerEdgeColor',seedEdge, ...
        'LineWidth',0.85);
end

% Mean +/- sample SD.  Draw the horizontal whiskers manually for robust R2021b support.
meanColor = C(3,:);
capHalfHeight = 0.075;
for k = 1:4
    xlo = meanVals(k) - sdVals(k);
    xhi = meanVals(k) + sdVals(k);
    plot(ax3,[xlo xhi],[yRow(k) yRow(k)],'-','Color',meanColor,'LineWidth',1.15);
    plot(ax3,[xlo xlo],[yRow(k)-capHalfHeight yRow(k)+capHalfHeight],'-','Color',meanColor,'LineWidth',1.0);
    plot(ax3,[xhi xhi],[yRow(k)-capHalfHeight yRow(k)+capHalfHeight],'-','Color',meanColor,'LineWidth',1.0);
end
hMean = plot(ax3,meanVals,yRow,'d', ...
    'LineStyle','none', ...
    'MarkerSize',6.4, ...
    'MarkerFaceColor',meanColor, ...
    'MarkerEdgeColor',meanColor, ...
    'LineWidth',1.0);

% Zero = no penalty.
xline(ax3,0,'--','Color',[0.48 0.48 0.48],'LineWidth',0.75);

% Light divider between EVA and ETU rows.
yline(ax3,2.5,':','Color',[0.78 0.78 0.78],'LineWidth',0.65);

% Axis range follows the actual data but leaves calm white space for the legend.
xMaxData = max([seedVals(:); (meanVals(:)+sdVals(:))]);
xMax = max(1.15, 1.06*xMaxData);
xlim(ax3,[-0.04 xMax]);
ylim(ax3,[0.45 4.88]);
xticks(ax3,0:0.2:1.2);

% MATLAB requires ascending YTick values.  The plotting rows [4 3 2 1]
% are deliberately top-to-bottom (EVA FP32, EVA Wiener, ETU FP32,
% ETU Wiener).  Reverse the labels to match ascending tick positions.
rowLabelsTopDown = { ...
    'EVA / FP32', ...
    'EVA / Wiener', ...
    'ETU / FP32', ...
    'ETU / Wiener'};
tickPositionsAscending = sort(yRow);    % [1 2 3 4]
tickLabelsAscending = fliplr(rowLabelsTopDown);
set(ax3,'YTick',tickPositionsAscending,'YTickLabel',tickLabelsAscending);

xlabel(ax3,'W8A8 - reference 2%-BER threshold (dB)', ...
    'FontName',fontName,'FontSize',fontSize);

% Use normalized text instead of axes title so R2021b cannot squeeze it away.
text(ax3,0.50,1.045,'(c) Paired 2%-BER threshold penalty', ...
    'Units','normalized','HorizontalAlignment','center', ...
    'VerticalAlignment','bottom','FontName',fontName, ...
    'FontSize',fontSize+0.5,'FontWeight','bold','Clipping','off');

set(ax3, ...
    'FontName',fontName, ...
    'FontSize',fontSize, ...
    'LineWidth',axisLineWidth, ...
    'TickDir','out', ...
    'TickLength',[0.010 0.010], ...
    'Layer','top', ...
    'XGrid','on', ...
    'YGrid','off', ...
    'GridLineStyle',':', ...
    'GridAlpha',0.14);

% Robust in-panel symbol key.  This is drawn manually rather than with
% legend(), because R2021b can suppress/reposition a second legend when the
% figure also contains the shared nine-method BER legend above.
legendY = 4.64;
legendX = [0.02 0.21 0.40 0.60];
legendTxt = {'Seed 1','Seed 2','Seed 3','Mean \pm sample SD'};
for s = 1:3
    plot(ax3,legendX(s),legendY, ...
        'LineStyle','none','Marker',seedMarkers{s}, ...
        'MarkerSize',4.8,'MarkerFaceColor','w', ...
        'MarkerEdgeColor',seedEdge,'LineWidth',0.85, ...
        'HandleVisibility','off');
    text(ax3,legendX(s)+0.025,legendY,legendTxt{s}, ...
        'VerticalAlignment','middle','HorizontalAlignment','left', ...
        'FontName',fontName,'FontSize',fontSize-0.8,'Color',[0.20 0.20 0.20], ...
        'Clipping','off');
end
plot(ax3,legendX(4),legendY,'d', ...
    'LineStyle','none','MarkerSize',6.2, ...
    'MarkerFaceColor',meanColor,'MarkerEdgeColor',meanColor, ...
    'LineWidth',1.0,'HandleVisibility','off');
text(ax3,legendX(4)+0.025,legendY,legendTxt{4}, ...
    'VerticalAlignment','middle','HorizontalAlignment','left', ...
    'FontName',fontName,'FontSize',fontSize-0.8,'Color',[0.20 0.20 0.20], ...
    'Clipping','off');

%% Export
pdfFile = fullfile(scriptDir,'fig5_matlab_publication_v4_fixed.pdf');
svgFile = fullfile(scriptDir,'fig5_matlab_publication_v4_fixed.svg');
pngFile = fullfile(scriptDir,'fig5_matlab_publication_v4_fixed.png');

exportgraphics(fig,pdfFile,'ContentType','vector','BackgroundColor','white');
set(fig,'PaperPositionMode','auto');
print(fig,svgFile,'-dsvg','-painters');
exportgraphics(fig,pngFile,'Resolution',600,'BackgroundColor','white');

fprintf('\nFig. 5 v4 fixed exported to:\n  %s\n  %s\n  %s\n',pdfFile,svgFile,pngFile);

%% -------------------------- local functions --------------------------
function h = plotBerPanel(ax, panel, methods, C, lineStyles, markers, ...
    isMain, targetBER, mainLW, refLW, errLW, markerMain, markerRef)

    hold(ax,'on');
    snr = panel.snr_db(:);
    h = gobjects(1,numel(methods));

    % Plot low-priority references first, then highlighted curves on top.
    order = [find(~isMain), find(isMain)];

    for jj = 1:numel(order)
        k = order(jj);
        key = methods{k};
        S = panel.methods.(key);
        mu = S.ber_mean(:);
        sd = S.ber_sample_sd(:);

        if isMain(k)
            lw = mainLW;
            ms = markerMain;
        else
            lw = refLW;
            ms = markerRef;
        end

        h(k) = errorbar(ax, snr, mu, sd, sd, ...
            'LineStyle',lineStyles{k}, ...
            'Marker',markers{k}, ...
            'MarkerSize',ms, ...
            'MarkerFaceColor','w', ...
            'MarkerEdgeColor',C(k,:), ...
            'Color',C(k,:), ...
            'LineWidth',lw, ...
            'CapSize',2);

        % Keep error bars visually lighter than the curve when possible.
        % (MATLAB R2021b errorbar does not expose independent whisker alpha.)
        try
            h(k).Bar.LineWidth = errLW;
        catch
            % No-op: line styling above remains publication-safe.
        end
    end

    yline(ax, targetBER, '--', '2% BER', ...
        'Color',[0.38 0.38 0.38], ...
        'LineWidth',0.75, ...
        'LabelHorizontalAlignment','left', ...
        'LabelVerticalAlignment','bottom', ...
        'FontSize',7.2);
end

function formatBerAxes(ax, panelTitle, fontName, fontSize, axisLineWidth)
    set(ax,'YScale','log');
    xlim(ax,[-0.4 28.4]);
    ylim(ax,[3e-4 4e-1]);
    xticks(ax,0:4:28);
    yticks(ax,[1e-3 1e-2 1e-1]);

    xlabel(ax,'E_s/N_0 (dB)', ...
        'FontName',fontName,'FontSize',fontSize);
    ylabel(ax,'Bit-error rate (BER)', ...
        'FontName',fontName,'FontSize',fontSize);
    title(ax,panelTitle, ...
        'FontName',fontName,'FontSize',fontSize+0.5, ...
        'FontWeight','bold','HorizontalAlignment','left');

    set(ax, ...
        'FontName',fontName, ...
        'FontSize',fontSize, ...
        'LineWidth',axisLineWidth, ...
        'TickDir','out', ...
        'TickLength',[0.012 0.012], ...
        'Layer','top', ...
        'Box','on', ...
        'XGrid','off', ...
        'YGrid','on', ...
        'GridLineStyle',':', ...
        'GridAlpha',0.16, ...
        'YMinorGrid','off');
end
